#!/usr/bin/env python3
"""Build the status screen's fonts as LVGL 8 font files (lv_font_fmt_txt, 4 bpp, no kerning).

    python3 tools/screen/fontgen.py ROBOTO.ttf firmware/JcorpNomadProject/nomad_status_fonts.c

ROBOTO.ttf is the variable Roboto from Google Fonts (OFL-1.1); each font below picks a named
instance from it. Needs only Python and Pillow (no lv_font_conv). Each font lists its own
characters (the big one is digits only).
"""
import sys
from PIL import ImageFont

ASCII = list(range(0x20, 0x7F))
EXTRA = [0x00B7, 0x2026]   # middle dot, ellipsis
FONTS = [
    # C name,             instance,  px, characters
    ("nomad_font_big",   "Bold",     44, [ord(c) for c in " 0123456789,.%"]),
    ("nomad_font_title", "Bold",     28, ASCII + EXTRA),
    ("nomad_font_head",  "Bold",     22, ASCII + EXTRA),
    ("nomad_font_body",  "Medium",   20, ASCII + EXTRA),
    ("nomad_font_small", "Medium",   16, ASCII + EXTRA),
    ("nomad_font_label", "Bold",     17, ASCII + EXTRA),   # the main screen's labels
    ("nomad_font_count", "Bold",     54, [ord(c) for c in "0123456789"]),   # the count on the tree
]
BPP = 4


def glyphs_for(ttf, instance, px, chars):
    f = ImageFont.truetype(ttf, px)
    f.set_variation_by_name(instance)
    ascent, descent = f.getmetrics()
    out = []
    for cp in sorted(chars):
        ch = chr(cp)
        adv = f.getlength(ch)
        mask, (ox, oy) = f.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        px_rows = [[mask.getpixel((x, y)) for x in range(w)] for y in range(h)]
        # trim empty rows and columns (the mask is padded on some glyphs)
        while px_rows and not any(px_rows[0]):
            px_rows.pop(0); oy += 1
        while px_rows and not any(px_rows[-1]):
            px_rows.pop()
        if px_rows:
            while not any(r[0] for r in px_rows):
                px_rows = [r[1:] for r in px_rows]; ox += 1
            while not any(r[-1] for r in px_rows):
                px_rows = [r[:-1] for r in px_rows]
        bw = len(px_rows[0]) if px_rows else 0
        bh = len(px_rows)
        out.append(dict(cp=cp, adv=adv, w=bw, h=bh, ox=ox, oy=-(oy + bh), rows=px_rows))
    return out, ascent, descent


def pack(rows):
    """4 bpp, rows run on without padding, the glyph starts on a byte."""
    vals = [min(15, (v * 15 + 127) // 255) for r in rows for v in r]
    if len(vals) % 2:
        vals.append(0)
    return bytes((vals[i] << 4) | vals[i + 1] for i in range(0, len(vals), 2))


def emit(name, instance, px, glyphs, ascent, descent):
    bitmap = bytearray()
    dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0 */"]
    for g in glyphs:
        idx = len(bitmap)
        bitmap += pack(g["rows"])
        dsc.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d} /* U+%04X */"
                   % (idx, round(g["adv"] * 16), g["w"], g["h"], g["ox"], g["oy"], g["cp"]))
    lines = []
    lines.append("/* %s: Roboto %s %d px, %d bpp, generated by tools/screen/fontgen.py */" % (name, instance, px, BPP))
    lines.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t %s_bitmap[] = {" % name)
    for i in range(0, len(bitmap), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 24]) + ",")
    lines.append("};")
    lines.append("static const lv_font_fmt_txt_glyph_dsc_t %s_dsc[] = {" % name)
    lines.append(",\n".join(dsc))
    lines.append("};")
    base = glyphs[0]["cp"]
    ofs = ", ".join("0x%x" % (g["cp"] - base) for g in glyphs)
    lines.append("static const uint16_t %s_cps[] = {%s};" % (name, ofs))
    lines.append("static const lv_font_fmt_txt_cmap_t %s_cmaps[] = {" % name)
    lines.append("    {.range_start = 0x%x, .range_length = 0x%x, .glyph_id_start = 1, .unicode_list = %s_cps,"
                 % (base, glyphs[-1]["cp"] - base + 1, name))
    lines.append("     .glyph_id_ofs_list = NULL, .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}," % len(glyphs))
    lines.append("};")
    lines.append("static lv_font_fmt_txt_glyph_cache_t %s_cache;" % name)
    lines.append("static const lv_font_fmt_txt_dsc_t %s_fdsc = {" % name)
    lines.append("    .glyph_bitmap = %s_bitmap, .glyph_dsc = %s_dsc, .cmaps = %s_cmaps, .kern_dsc = NULL," % (name, name, name))
    lines.append("    .kern_scale = 0, .cmap_num = 1, .bpp = %d, .kern_classes = 0, .bitmap_format = 0," % BPP)
    lines.append("    .cache = &%s_cache" % name)
    lines.append("};")
    lines.append("const lv_font_t %s = {" % name)
    lines.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    lines.append("    .line_height = %d, .base_line = %d, .subpx = LV_FONT_SUBPX_NONE," % (ascent + descent, descent))
    lines.append("    .underline_position = -2, .underline_thickness = 1, .dsc = &%s_fdsc, .fallback = NULL, .user_data = NULL" % name)
    lines.append("};")
    return "\n".join(lines)


def main():
    ttf, out = sys.argv[1], sys.argv[2]
    parts = ["/* The status screen's fonts, from Roboto (OFL-1.1). Generated: do not edit by hand. */",
             "#include <lvgl.h>", ""]
    for name, inst, px, chars in FONTS:
        g, a, d = glyphs_for(ttf, inst, px, chars)
        parts.append(emit(name, inst, px, g, a, d))
        parts.append("")
    open(out, "w").write("\n".join(parts))


if __name__ == "__main__":
    main()
