#!/usr/bin/env python3
"""Build the status screen's icons as LVGL 8 alpha-only images (LV_IMG_CF_ALPHA_8BIT).

    python3 tools/screen/icongen.py firmware/JcorpNomadProject/nomad_status_icons.c [--png DIR]

Sources are the SVGs in tools/screen/icons (see the README there: Material Design Icons and
Material Symbols, both Apache-2.0). The big icons are drawn at BIG px, the media-type icons
(k-*.svg, the scan's legend) at SMALL px. The screen colours them (img_recolor), so one image
serves every state. Needs Inkscape on the PATH to turn the SVG into pixels.
"""
import os, subprocess, sys, tempfile
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ICONS = os.path.join(HERE, "icons")
BIG = 112
SMALL = 24
COMPACT = 80
COMPACT_NAMES = ["folder"]   # also drawn at COMPACT px (_80), for pages with a big number
# the main screen's own sizes; x-*.svg files are drawn only here
MAIN_SIZES = [("card", 35), ("wifi", 35), ("x-people", 22)]


def render(svg, px, tmp):
    png = os.path.join(tmp, os.path.basename(svg) + ".png")
    subprocess.run(["inkscape", svg, "--export-type=png", "--export-filename=" + png,
                    "-w", str(px), "-h", str(px)], check=True, capture_output=True)
    return Image.open(png).convert("RGBA").getchannel("A")


def main():
    out = sys.argv[1]
    png_dir = sys.argv[sys.argv.index("--png") + 1] if "--png" in sys.argv else None
    names = sorted(f[:-4] for f in os.listdir(ICONS) if f.endswith(".svg"))
    jobs = [(n, n, SMALL if n.startswith("k-") else BIG) for n in names if not n.startswith("x-")]
    jobs += [(n, n + "-80", COMPACT) for n in COMPACT_NAMES]
    jobs += [(n, n.replace("x-", "") + "-%d" % px, px) for n, px in MAIN_SIZES]
    lines = ["/* The status screen's icons, alpha only. Generated by tools/screen/icongen.py from",
             "   tools/screen/icons (Material Design Icons, Material Symbols: Apache-2.0). Do not edit. */",
             "#include <lvgl.h>", ""]
    with tempfile.TemporaryDirectory() as tmp:
        for src, name, px in jobs:
            a = render(os.path.join(ICONS, src + ".svg"), px, tmp)
            if png_dir:
                os.makedirs(png_dir, exist_ok=True); a.save(os.path.join(png_dir, name + ".png"))
            cname = "nomad_icon_" + name.replace("-", "_")
            data = a.tobytes()
            lines.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t %s_map[] = {" % cname)
            for i in range(0, len(data), 28):
                lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 28]) + ",")
            lines.append("};")
            lines.append("const lv_img_dsc_t %s = {" % cname)
            lines.append("    .header = {.cf = LV_IMG_CF_ALPHA_8BIT, .always_zero = 0, .reserved = 0, .w = %d, .h = %d}," % (px, px))
            lines.append("    .data_size = %d, .data = %s_map};" % (len(data), cname))
            lines.append("")
    open(out, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
